            <p>O início de um tratamento já costuma ser um momento extremamente delicado para o paciente e sua família. Mas, em muitos casos, além da preocupação com a própria saúde, ainda surge outro problema:  <strong>a negativa do plano de saúde para o fornecimento do medicamento prescrito.</strong></p>

<p>E normalmente essas negativas vêm acompanhadas de justificativas como:

</p><p>“O medicamento não está no rol da ANS”;</p>
<p>“O contrato não cobre esse tratamento”;</p>
<p>“Existe outro medicamento disponível”;</p>
<p>ou até alegações de que o tratamento seria experimental.</p>

O ponto importante é que o fato de o plano negar o medicamento não significa, automaticamente, que essa recusa seja legal.


<p>Em muitos casos, principalmente quando existe  <strong>urgência ou risco de interrupção do tratamento,</strong> uma atuação rápida e estratégica faz toda diferença na condução do caso e para a preservação da saúde do paciente. Por isso, a análise individualizada por um advogado especializado em Direito da Saúde pode ser importante para compreender quais medidas são mais adequadas em cada situação.</p>

<p><strong>O que fazer após a negativa do plano?</strong></p>

<p> <strong>Primeiro:</strong> Solicitar a negativa por escrito, juntamente com o motivo da recusa do plano de saúde.

</p><p>Como? Esse pedido pode ser feito diretamente pelos canais de atendimento da operadora, como SAC e ouvidoria. Também é importante anotar os números de protocolo e guardar todos os registros relacionados ao atendimento, pois podem servir de prova em uma eventual ação judicial.</p>

<p> <strong>Segundo:</strong> Além disso, já é fundamental reunir toda a documentação médica relacionada ao caso, como:</p>

<p>- exames;</p>
<p>- laudos;</p>
<p>- histórico da doença;</p>
<p>- relatório médico;</p>
<p>- e a prescrição detalhada do medicamento.</p>

<p> <strong>Terceiro:</strong> Registrar uma reclamação na ANS:

Além do contato direto com o plano de saúde, o paciente também pode registrar reclamação na Agência Nacional de Saúde Suplementar (ANS). Esse registro ajuda a demonstrar a tentativa prévia de resolução do problema e pode se tornar um documento importante para eventual ação judicial, além de reforçar os registros relacionados à negativa do tratamento.</p>

<p><strong>Entenda o que está por trás das justificativas usadas pelo plano de saúde</strong></p>

<p><strong>1- “O medicamento não está no rol da ANS”</strong></p>

<p>Essa é uma das justificativas mais utilizadas pelos planos de saúde. Mas o fato de o medicamento não constar no rol da ANS não significa, automaticamente, que a negativa seja correta.

O rol funciona como uma cobertura mínima obrigatória dos planos de saúde e, dependendo do caso, pode haver discussão sobre a necessidade de cobertura do tratamento prescrito pelo médico responsável.</p>

<p><strong>2- “Existe outro medicamento disponível”</strong></p>

<p>Também são comuns situações em que o plano tenta substituir o medicamento prescrito por outra medicação mais barata ou diferente da indicada pelo médico.

Mas é importante lembrar que não cabe ao plano de saúde definir qual é o melhor tratamento para o paciente, e sim ao médico responsável pelo acompanhamento daquele caso.</p>

<p><strong>3-“O tratamento é experimental”</strong></p>

<p>Outra justificativa bastante frequente é a alegação de que o tratamento seria experimental.

Mas nem todo tratamento moderno, recente ou de alto custo pode ser considerado experimental automaticamente. Essa análise depende de fatores como indicação médica, estudos científicos relacionados ao medicamento e as necessidades específicas do paciente.</p>

<p><strong>4-“O contrato não cobre esse tratamento”</strong></p>

<p>Em alguns casos, a negativa também é fundamentada em cláusulas contratuais de exclusão de cobertura.

Mas, principalmente em situações envolvendo tratamentos essenciais, urgência ou risco à saúde do paciente, essa análise não pode ser feita de forma automática ou genérica, sendo importante avaliar as circunstâncias específicas de cada caso.</p>

<p><strong>E QUANTO À NECESSIDADE DE AJUIZAR AÇÃO JUDICIAL?</strong></p>

<p>Quando a negativa compromete o início ou a continuidade do tratamento (principalmente em situações urgentes), pode ser necessária uma atuação jurídica rápida e estratégica, inclusive com eventual ajuizamento de ação judicial com <strong>pedido liminar,</strong> justamente para tentar garantir o fornecimento do medicamento em tempo adequado e evitar prejuízos ainda maiores à saúde do paciente. 

</p><p>Por isso, diante desse tipo de situação, é essencial a análise individualizada por um advogado especializado em Direito da Saúde para avaliar a legalidade da negativa e definir quais medidas são mais adequadas para cada caso.</p>

